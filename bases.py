#!/usr/bin/python3
import sys
n = int(sys.argv[1])
n2 = bin(n)
n8 = oct(n)
n16 = hex(n)
print("в двоичной", n2, "в восьмеричной", n8, "в шестнадцатеричной", n16)
n10_2 = int( n2[2:], 2)
n10_8 = int(n8[2:], 8)
n10_16 = int(n16[2:], 16)
print("перевод получившихся чисел из двоичной, восьмеричной и шестнадцатеричной систем соответственно равен", n10_2, n10_8, n10_16)
