#!/usr/bin/python3
a = input()
k = len(a)
print("количество букв =",k)
print("первый символ -",a[0], "последний символ -",a[-1])
s = k // 2 
if k % 2 != 0:
    print("средний символ -",a[s])
print("четные буквы -", a[1::2])
print("нечетные беквы-", a[::2])
j = a[::-1]
print("наоборот-", j)
if a == a[::-1]:
    print("это палиндром")
else:
    print("это не палиндром")


